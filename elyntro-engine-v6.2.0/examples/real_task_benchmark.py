"""Deterministic end-to-end benchmark for Elyntro's canonical cognitive path.

This validates planning -> registered handlers -> artifacts -> independent verification.
It does NOT measure foundation-model intelligence, web research, image/video generation,
or external computer-use performance; all handlers are local and deterministic.
Run from the project root: python examples/real_task_benchmark.py
"""
from __future__ import annotations

import json
import math
import tempfile
import time
import sys
from pathlib import Path
from typing import Any, Callable

# Allow direct execution as `python examples/real_task_benchmark.py`.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from elyntro import (
    CognitiveLoop, Engine, EvidenceVerifier, RuleBasedPlanner, SQLiteStore,
    StepResult, TaskExecutor, TaskRequest, TaskStatus, ToolDefinition,
)


def make_case(name: str, goal: str, criterion: str, tools: list[ToolDefinition],
              handlers: dict[str, Callable], verifier: EvidenceVerifier,
              expected_status: TaskStatus = TaskStatus.SUCCEEDED) -> dict[str, Any]:
    return {"name": name, "goal": goal, "criterion": criterion, "tools": tools,
            "handlers": handlers, "verifier": verifier, "expected_status": expected_status}


def build_cases() -> list[dict[str, Any]]:
    html_goal = "Create a responsive web page for a student project"
    html_criterion = "responsive_page_is_valid"
    html = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Student Project</title><style>body{font-family:system-ui;margin:0;padding:2rem}
@media (max-width:600px){body{padding:1rem}}</style></head>
<body><main><h1>Student Project</h1><p>A responsive sample page.</p></main></body></html>"""

    def simple_stage(key: str):
        def handler(inputs, context):
            return StepResult(output={"stage": key, "completed": True})
        return handler

    def create_page(inputs, context):
        return StepResult(
            output={"file": "index.html", "bytes": len(html.encode("utf-8"))},
            evidence=[{"criterion": html_criterion, "detail": "HTML artifact generated by the create handler"}],
            artifacts=[{"name": "index.html", "content": html, "media_type": "text/html"}],
        )
    html_verifier = EvidenceVerifier()
    def verify_html(criterion, evidence, context):
        content = next((a.get("content", "") for a in context.get("artifacts", []) if a.get("name") == "index.html"), "")
        normalized = content.casefold()
        return all(token in normalized for token in ('<html', '<title>', 'name="viewport"', '@media', '<h1>'))
    html_verifier.register(html_criterion, verify_html)
    html_tools = [ToolDefinition("researcher", "Gather requirements", ("research",)),
                  ToolDefinition("creator", "Build HTML page", ("create",)),
                  ToolDefinition("checker", "Review generated page", ("verify",))]
    html_handlers = {"researcher": simple_stage("research"), "creator": create_page, "checker": simple_stage("verify")}

    sales_criterion = "sales_analysis_is_correct"
    sales = [120.0, 80.0, 150.0, 50.0]
    sales_result = {"count": len(sales), "total": sum(sales), "mean": sum(sales) / len(sales), "max": max(sales)}
    def analyze_sales(inputs, context):
        return StepResult(output=sales_result,
            evidence=[{"criterion": sales_criterion, "detail": "analysis artifact computed from supplied sample values"}],
            artifacts=[{"name": "sales_analysis.json", "content": sales_result, "media_type": "application/json"}])
    sales_verifier = EvidenceVerifier()
    def verify_sales(criterion, evidence, context):
        artifact = next((a.get("content") for a in context.get("artifacts", []) if a.get("name") == "sales_analysis.json"), None)
        return isinstance(artifact, dict) and artifact.get("count") == 4 and artifact.get("total") == 400.0 and artifact.get("mean") == 100.0 and artifact.get("max") == 150.0
    sales_verifier.register(sales_criterion, verify_sales)
    sales_tools = [ToolDefinition("researcher", "Prepare sales data", ("research",)),
                   ToolDefinition("analyst", "Analyze sales values", ("analyze",)),
                   ToolDefinition("checker", "Check analysis", ("verify",))]
    sales_handlers = {"researcher": simple_stage("research"), "analyst": analyze_sales, "checker": simple_stage("verify")}

    finance_criterion = "compound_interest_is_correct"
    expected_amount = 1000 * (1 + 0.05) ** 3
    def calculate_interest(inputs, context):
        result = {"principal": 1000.0, "annual_rate": 0.05, "years": 3, "final_amount": round(expected_amount, 3)}
        return StepResult(output=result,
            evidence=[{"criterion": finance_criterion, "detail": "calculation artifact produced"}],
            artifacts=[{"name": "compound_interest.json", "content": result, "media_type": "application/json"}])
    finance_verifier = EvidenceVerifier()
    def verify_interest(criterion, evidence, context):
        artifact = next((a.get("content") for a in context.get("artifacts", []) if a.get("name") == "compound_interest.json"), None)
        return isinstance(artifact, dict) and math.isclose(artifact.get("final_amount", float("nan")), expected_amount, rel_tol=0, abs_tol=0.001)
    finance_verifier.register(finance_criterion, verify_interest)
    finance_tools = [ToolDefinition("calculator", "Calculate compound interest", ("analyze",)),
                     ToolDefinition("checker", "Check financial calculation", ("verify",))]
    finance_handlers = {"calculator": calculate_interest, "checker": simple_stage("verify")}

    deceptive_criterion = "unverified_claim_is_not_accepted"
    def unsupported_claim(inputs, context):
        return StepResult(output={"claimed_success": True}, evidence=[
            {"criterion": deceptive_criterion, "detail": "handler says this is correct, but supplies no independently checkable artifact"}
        ])
    deceptive_verifier = EvidenceVerifier()  # Deliberately no validator: expected NEEDS_APPROVAL.
    deceptive_tools = [ToolDefinition("researcher", "Prepare task context", ("research",)),
                        ToolDefinition("analyzer", "Process task", ("analyze",)),
                        ToolDefinition("checker", "Review result", ("verify",))]
    deceptive_handlers = {"researcher": simple_stage("research"), "analyzer": unsupported_claim, "checker": simple_stage("verify")}

    return [
        make_case("responsive_html_artifact", html_goal, html_criterion, html_tools, html_handlers, html_verifier),
        make_case("sales_data_analysis", "Analyze sales data and calculate total, mean, and maximum", sales_criterion, sales_tools, sales_handlers, sales_verifier),
        make_case("compound_interest_calculation", "Calculate compound interest for 1000 at 5 percent for 3 years", finance_criterion, finance_tools, finance_handlers, finance_verifier),
        make_case("reject_unverified_success_claim", "Analyze a result without proof", deceptive_criterion, deceptive_tools, deceptive_handlers, deceptive_verifier, TaskStatus.NEEDS_APPROVAL),
    ]


def run_case(case: dict[str, Any]) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="elyntro-benchmark-") as directory:
        store = SQLiteStore(Path(directory) / "tasks.sqlite")
        engine = Engine(store)
        executor = TaskExecutor(engine, case["handlers"])
        loop = CognitiveLoop(engine, RuleBasedPlanner(), case["tools"], executor, verifier=case["verifier"])
        start = time.perf_counter()
        result = loop.run(TaskRequest(goal=case["goal"], success_criteria=[case["criterion"]]))
        elapsed_ms = (time.perf_counter() - start) * 1000
        status = result.task.status
        report = result.verification or {}
        return {
            "name": case["name"], "expected_status": case["expected_status"].value,
            "actual_status": status.value, "pass": status == case["expected_status"],
            "verification_status": report.get("status", "missing"),
            "artifacts": [artifact.get("name") for artifact in result.task.artifacts],
            "steps_planned": len(result.plan.steps) if result.plan else 0,
            "elapsed_ms": round(elapsed_ms, 3),
        }


def main() -> int:
    results = [run_case(case) for case in build_cases()]
    passed = sum(row["pass"] for row in results)
    report = {
        "benchmark": "Elyntro deterministic end-to-end task benchmark",
        "scope": "Local integration benchmark; no external model/provider calls",
        "cases": len(results), "passed": passed, "failed": len(results) - passed,
        "pass_rate": round(passed / len(results), 4) if results else 0,
        "mean_latency_ms": round(sum(row["elapsed_ms"] for row in results) / len(results), 3) if results else 0,
        "results": results,
        "limitations": [
            "Does not measure general intelligence or foundation-model reasoning.",
            "Does not test external web research, deployment, image/audio/video generation, or computer use.",
            "Latency is local runtime overhead and is not comparable to hosted inference latency.",
        ],
    }
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
